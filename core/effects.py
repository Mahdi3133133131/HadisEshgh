"""
افکت پیام — همان رنگ‌وریسه‌ای که تلگرام روی کل صفحهٔ گفتگو می‌پاشد.

## چرا یک پروندهٔ جدا برای دو عدد

این شناسه‌ها عددهای بی‌معنایند و هیچ‌کس با دیدنشان نمی‌فهمد کدام
افکت‌اند. همین بود که یک بار لغزاند: شناسهٔ **آتش** در کد نشسته
بود و کنارش نوشته شده بود «🎉». کسی که کد را می‌خواند باور می‌کرد
کانفتی می‌بارد، حال آنکه کاربر آتش می‌دید.

اکنون هر شناسه یک نام دارد و نامش همان چیزی است که کاربر می‌بیند.

## دو نکته که تلگرام سخت‌گیر است

۱) افکت **تنها در گفتگوی خصوصی** کار می‌کند. در گروه، تلگرام کل
   پیام را با خطا رد می‌کند — نه اینکه افکت را نادیده بگیرد. پس
   `for_chat` وجود دارد تا هیچ‌کس این را از یاد نبرد.

۲) از Bot API 7.10 آمده. اگر روزی سرور قدیمی‌تری در کار باشد،
   فرستادن با خطا برمی‌گردد؛ فراخوان باید بتواند بی افکت هم
   بفرستد.
"""

from __future__ import annotations

# نامِ هر افکت، همان چیزی است که کاربر روی پرده می‌بیند.
PARTY = "5046509860389126442"      # 🎉 کانفتی
FIRE = "5104841245755180586"       # 🔥 آتش
THUMBS_UP = "5107584321108051014"  # 👍
HEART = "5044134455711629726"      # ❤️


def for_chat(chat_id: int, effect: str = PARTY) -> dict:
    """
    آرگومان افکت، اگر این گفتگو بپذیردش — وگرنه تهی.

    به شکل دیکشنری برمی‌گردد تا با `**` در فراخوان باز شود و
    فراخوان ناچار به شرط‌نویسی نباشد:

        await bot.send_audio(..., **effects.for_chat(chat_id))

    شناسهٔ مثبت یعنی گفتگوی خصوصی؛ گروه و کانال شناسهٔ منفی
    دارند.
    """
    return {"message_effect_id": effect} if chat_id > 0 else {}
