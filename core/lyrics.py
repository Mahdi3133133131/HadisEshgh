"""
تطبیق متن — یافتن نوا از روی آنچه خوانده می‌شود.

## چرا تطبیقِ ساده بس نیست

رونویسیِ ماشینی هرگز بی‌عیب نیست: واژه‌ای جا می‌افتد، واژه‌ای غلط
شنیده می‌شود، و نیم‌فاصله و املا میان دو رونویسی فرق می‌کند. پس
جست‌وجوی رشتهٔ خام (`LIKE %...%`) نزدیک به هیچ می‌یابد — یک واژهٔ
غلط در میانه، کل تطبیق را می‌شکند.

## آنچه اینجا هست: هم‌پوشانیِ واژگان

سنجیده می‌شود چه کسری از واژه‌های **کلیپ** در متنِ نوا هست.

═══════════════════════════════════════════════════════════
  چرا واژهٔ تنها، و نه دوتایی و سه‌تایی
═══════════════════════════════════════════════════════════

گمانِ نخستِ من سه‌تایی بود، بر این پندار که «سه واژهٔ پیاپی اثری
است که کمتر تصادفی تکرار می‌شود». سنجش ردش کرد.

با واژگانِ جدا برای هر نوا و خطای آواییِ رونویسی، جداییِ کمینهٔ
درست از بیشینهٔ کاذب چنین شد:

    پنجره   خطای ۰٪   خطای ۲۰٪   خطای ۳۰٪   خطای ۴۰٪
      ۱      +۰٫۵۰     +۰٫۱۵      +۰٫۱۶      +۰٫۱۰
      ۲      +۰٫۹۱     هم‌پوشان   +۰٫۰۹      هم‌پوشان
      ۳      +۱٫۰۰     هم‌پوشان   هم‌پوشان   هم‌پوشان

سه‌تایی در رونویسیِ بی‌عیب بی‌نظیر است و به‌محض نخستین خطا فرو
می‌ریزد — چون یک واژهٔ غلط، سه سه‌تایی را با هم می‌کشد. و رونویسیِ
**آواز** بی‌عیب نیست؛ خواندن از گفتار سخت‌تر است.

پس واژهٔ تنها، که تنها خودش را می‌بازد.

## چرا این لایه رأی می‌دهد، نه داوری

جدایی در بهترین حالت ۰٫۱۰ تا ۰٫۱۶ است — بس برای «این نشانه‌ای
است»، نه برای «این همان است». پس متن به‌تنهایی هیچ نوایی را
برنده نمی‌کند؛ کنارِ نشانهٔ دیگری می‌نشیند و استوارش می‌کند.

همان کاری که شنوندهٔ آشنا می‌کند: نه از متن تنها، نه از صدا
تنها — از هم‌خوانیِ آن‌ها.
"""

from __future__ import annotations

from core.normalize import normalize

# اندازهٔ پنجرهٔ واژگانی. یک، بر پایهٔ سنجش — بالای آن با
# نخستین خطای رونویسی فرو می‌ریزد.
GRAM = 1

# کمتر از این شمار واژه، هم‌پوشانی معناداری نمی‌سازد — دو واژه
# در هر متنی پیدا می‌شود.
MIN_WORDS = 5

# زیر این هم‌پوشانی، چیزی گفته نمی‌شود.
#
# بیشینهٔ امتیازِ نوای بیگانه در سنجش ۰٫۵۰ بود؛ این کمی بالاترش
# است. بهایش آن است که کلیپی با خطای رونویسیِ بسیار بالا
# (بالای ۴۰٪) گواهی نمی‌دهد — و همین درست است: رونویسیِ بد نباید
# رأی بدهد.
MIN_OVERLAP = 0.52

# فاصله تا نامزد دوم. بی این، دو نوای هم‌مضمون هر دو برنده
# می‌شدند و کدام‌شان برنده است تصادفی می‌شد.
MIN_MARGIN = 0.12


def grams(text: str, size: int = GRAM) -> set[tuple[str, ...]]:
    """اثرِ واژگانیِ یک متنِ هنجارشده — با `size = 1`، مجموعهٔ واژه‌ها."""
    words = [w for w in normalize(text or "").split() if w]
    if len(words) < size:
        # متنِ کوتاه‌تر از پنجره، خودش یک اثر می‌شود — وگرنه
        # کلیپ‌های خیلی کوتاه هرگز تطبیق نمی‌یافتند.
        return {tuple(words)} if words else set()
    return {
        tuple(words[i : i + size]) for i in range(len(words) - size + 1)
    }


def overlap(clip_text: str, track_text: str) -> float:
    """
    چه کسری از اثرِ کلیپ در متنِ نوا هست — میان ۰ و ۱.

    نامتقارن است و باید باشد: کلیپ تکه‌ای از نواست، پس انتظار
    داریم اثرِ **کلیپ** در نوا پیدا شود، نه وارونه. سنجهٔ متقارن
    (ژاکار) کلیپِ ده‌ثانیه‌ای را در برابر نوای پنج‌دقیقه‌ای همیشه
    نزدیک صفر می‌داد.
    """
    clip = grams(clip_text)
    if not clip:
        return 0.0
    track = grams(track_text)
    if not track:
        return 0.0
    return len(clip & track) / len(clip)


def enough_words(text: str) -> bool:
    """آیا این رونویسی آن‌قدر هست که بشود بر آن تکیه کرد."""
    return len([w for w in normalize(text or "").split() if w]) >= MIN_WORDS


def best_match(
    clip_text: str, candidates: list[tuple[int, str]]
) -> tuple[int, float] | None:
    """
    نزدیک‌ترین نوا بر پایهٔ متن.

    آرگومان‌ها:
        clip_text: رونویسیِ کلیپ کاربر.
        candidates: فهرست (شناسهٔ نوا، متنِ نوا).

    بازگشتی: (شناسه، هم‌پوشانی) یا None. `None` پاسخِ درست و
    رایج است.

    دو نگهبان دارد — آستانهٔ مطلق، و فاصله تا نامزد دوم. تنها با
    آستانه، دو نوای هم‌مضمون هر دو رد می‌شدند یا هر دو می‌گذشتند.
    """
    if not enough_words(clip_text) or not candidates:
        return None

    scored = [
        (track_id, overlap(clip_text, text))
        for track_id, text in candidates
        if text
    ]
    if not scored:
        return None

    scored.sort(key=lambda item: -item[1])
    best_id, best = scored[0]
    if best < MIN_OVERLAP:
        return None

    runner_up = scored[1][1] if len(scored) > 1 else 0.0
    if best - runner_up < MIN_MARGIN:
        return None

    return best_id, best
