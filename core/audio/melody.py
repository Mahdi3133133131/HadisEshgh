"""
نشان خطِ آهنگ — لایهٔ سومِ تشخیص.

═══════════════════════════════════════════════════════════════
  چرا این لایه ساخته شد
═══════════════════════════════════════════════════════════════

اثر انگشت تنها **همان ضبط** را می‌یابد. اگر کاربر پاره‌ای از اجرای
زندهٔ یک نوحه بفرستد و در گنجینه نسخهٔ استودیوییِ همان نوحه باشد،
هیچ عدد مشترکی پدید نمی‌آید — هرچند گوش انسان هر دو را یک نوا
بشمارد. این کاستیِ ذاتیِ روش است، نه ایرادی که با تنظیم درست شود.

آن یکی از دو ناکامیِ چهار بازجویی نخستِ کاربر بود.

این لایه همان شکاف را می‌بندد: نشانی می‌سازد که به **گام** و
**سرعت** وابسته نیست، پس اجرای دیگر را با نسخهٔ گنجینه جور می‌کند.

═══════════════════════════════════════════════════════════════
  چگونه کار می‌کند
═══════════════════════════════════════════════════════════════

**۱. کروما به جای طیف.** طیف می‌گوید «چه بسامدهایی هست»؛ کروما
می‌گوید «کدام یک از دوازده نتِ گام». دو خوانندهٔ جدا با دو صدای
جدا، اگر یک آهنگ بخوانند، طیفشان یکی نیست ولی کرومایشان هست.

**۲. هموارسازی درازآهنگ.** کروما را روی چند فریم میانگین می‌گیریم
تا لرزش‌های کوتاه (تحریر، نفس، ضربِ دف) از میان برود و آنچه بماند
خطِ آهنگ باشد. همین است که این نشان را در برابر تفاوتِ اجرا
پایدار می‌کند.

**۳. هنجارسازیِ هر فریم.** بلندی صدا از نشان بیرون می‌رود؛ پژواک
مجلس و ضبطِ بلند یا آهسته دیگر اثری ندارند.

**۴. جابه‌جایی گام.** مداح هر شب در گام دیگری می‌خواند. دوازده
چرخشِ ممکن آزموده می‌شود و بهترینشان برداشته می‌گردد — پس نشان
نسبت به گام ناوابسته است.

**۵. هم‌بستگیِ لغزان.** پارهٔ کاربر روی سراسر نوا لغزانده می‌شود؛
بیشترین هم‌بستگی، هم می‌گوید «چقدر همانند» و هم «کجای نوا».

═══════════════════════════════════════════════════════════════
  آنچه این لایه نیست
═══════════════════════════════════════════════════════════════

جایگزین اثر انگشت نیست و هرگز نباید باشد. اثر انگشت **قطعی**
می‌گوید؛ این یکی **محتمل**. ترتیبِ درست همیشه همان است: نخست اثر
انگشت، و تنها اگر چیزی نیافت، این.

دو نوحهٔ گوناگون که آهنگشان به هم می‌ماند — که در مداحی کم نیست —
اینجا همانند شمرده می‌شوند. برای همین آستانه‌اش بلند است و پاسخش
همیشه با «اجرای دیگری از همین نوا، شاید» می‌آید.
"""

from __future__ import annotations

import logging
from dataclasses import dataclass

import numpy as np

from core.audio.decode import SAMPLE_RATE

logger = logging.getLogger(__name__)

# نسخهٔ ساختار نشان. با بالا رفتنش، نشان‌های کهنه بازشناخته و از نو
# ساخته می‌شوند — نه آنکه خاموش نادرست بخوانند.
MELODY_VERSION = 1

# ── برداشت ───────────────────────────────────────────────────

# گام کرومای خام. ۲۰۴۸ نمونه در ۱۱۰۲۵ هرتز ≈ ۱۸۶ میلی‌ثانیه.
CHROMA_HOP = 2048

# چند فریم خام در یک فریمِ نشان هموار می‌شود. ۸ فریم ≈ ۱٫۵ ثانیه —
# درازتر از یک تحریر، کوتاه‌تر از یک مصرع. همین اندازه است که
# لرزشِ اجرا را می‌زداید و خطِ آهنگ را نگه می‌دارد.
SMOOTH = 8

# فریم‌های نشان چند تا در ثانیه‌اند (پس از هموارسازی)
FRAMES_PER_SECOND = SAMPLE_RATE / CHROMA_HOP / SMOOTH  # ≈ ۰٫۶۷

# کوتاه‌تر از این، نشانی ساخته نمی‌شود؛ خطِ آهنگ در چند ثانیه
# پیدا نیست.
MIN_SECONDS = 12.0

# ── تطبیق ────────────────────────────────────────────────────

# زیر این هم‌بستگی، هیچ گفته نمی‌شود.
#
# ═══════════════════════════════════════════════════════════
#   این عدد سنجیده شده است، نه گمانه‌زده
# ═══════════════════════════════════════════════════════════
#
# نخستین گمانِ من ۰٫۶۹ بود، بر این پندار که «کرومای هموارشده ذاتاً
# هم‌بستگی بالایی می‌دهد». سنجش گفت نادرست است: با ۱۰۸ جفتِ
# سنجیده روی شش نوحه و سه اجرای گوناگون از هر کدام (گام دیگر،
# سرعت دیگر، رنگ آوای دیگر، نویز)، توزیع چنین شد:
#
#     همان نوحه، اجرای دیگر : میانه ۰٫۷۷ · کمینه ۰٫۷۱
#     نوحهٔ دیگر            : میانه ۰٫۵۶ · بیشینه ۰٫۶۶
#
# جدایی کامل است — هیچ جفتِ درستی زیر هیچ جفتِ نادرستی نیفتاد. پس
# مرز میانِ ۰٫۶۶ و ۰٫۷۱ می‌نشیند. ۰٫۶۹ برگزیده شد: نزدیک‌تر به
# کمینهٔ درست تا بیشینهٔ نادرست، چون بهای «نگفتن» در این لایه از
# بهای «نادرست گفتن» کمتر است.
#
# با آستانهٔ گمانه‌زدهٔ ۰٫۶۹، این لایه **هرگز** چیزی نمی‌گفت.
MIN_SIMILARITY = 0.69

# و باید از دومین نامزد این‌قدر سر باشد. سنجش مطلق به‌تنهایی بس
# نیست؛ همان درسی که در لایهٔ آوا گرفتیم.
MIN_MARGIN = 0.04

# کمترین شمار نوا در گنجینه تا این لایه به کار بیفتد.
#
# ═══════════════════════════════════════════════════════════
#   چرا اینجا ۳ است و در لایهٔ رنگ آوا ۲۰
# ═══════════════════════════════════════════════════════════
#
# نخست اینجا هم ۸ گذاشتم، به تقلید از لایهٔ آوا. نادرست بود، و
# آزمون گرفتش: با شش نوحه در گنجینه، لایه یکسره خاموش می‌ماند و
# هیچ‌کدام از ۲۴ اجرا یافته نشد — حال آنکه توزیع‌ها به‌روشنی جدا
# بودند.
#
# تفاوت در جنسِ سنجش است:
#
#   • **رنگ آوا** نسبی می‌سنجد. برای هنجارسازی به میانگین و
#     انحراف معیارِ گنجینه نیاز دارد، و میانگینِ چهار بردار،
#     میانگین نیست. آنجا ۲۰ کمترین شمارِ معناداری است.
#
#   • **خطِ آهنگ** مطلق می‌سنجد. هم‌بستگیِ دو دنباله به هیچ نوای
#     سومی وابسته نیست؛ آستانهٔ ۰٫۶۹ از توزیعِ خودِ جفت‌ها درآمده،
#     نه از آمارِ گنجینه.
#
# پس تنها چیزی که اینجا کمترین شمار می‌خواهد، سنجشِ حاشیه نسبت به
# دومین نامزد است — و آن با سه نوا هم کار می‌کند.
MIN_CORPUS = 3

# ── پالودهٔ پیش‌دستی ─────────────────────────────────────────
#
# سنجشِ کاملِ هر نوا ۱۷ میلی‌ثانیه می‌برد (۵ نسبت سرعت × ۱۲ چرخش
# گام × لغزاندن). برای بیست نوا ناچیز است؛ برای پنج هزار نوا
# می‌شود یک دقیقه و نیم — و کاربر یک دقیقه و نیم چشم‌به‌راه
# نمی‌ماند.
#
# چاره: نخست با نمایهٔ درشتِ هر نوا (تنها دوازده عدد، میانگین
# کرومای سراسر نوا) کوتاه‌فهرستی ساخته می‌شود، و سنجش کامل تنها
# روی همان‌ها می‌رود. نمایهٔ درشت ضعیف است ولی تصادفی نیست: نوحه‌ای
# که خطِ آهنگش می‌خواند، میانگین کرومایش هم می‌خواند.
SHORTLIST = 40


@dataclass(frozen=True)
class MelodyMatch:
    """یک نوای گنجینه که خطِ آهنگش به پارهٔ کاربر می‌ماند."""

    track_id: int
    similarity: float
    offset_seconds: float
    semitones: int  # چند نیم‌پرده جابه‌جا — گام اجرای کاربر نسبت به گنجینه

    @property
    def confidence(self) -> float:
        """
        اطمینان میان ۰ و ۱.

        هم‌بستگیِ خام از ۰٫۶۹ به بالا معنا دارد، پس همان بازه به
        صفر تا یک کشیده می‌شود؛ وگرنه هر پاسخی «۸۸٪» می‌نمود و
        عددْ چیزی به کاربر نمی‌گفت.
        """
        span = 1.0 - MIN_SIMILARITY
        return float(np.clip((self.similarity - MIN_SIMILARITY) / span, 0.0, 1.0))


class MelodyError(RuntimeError):
    """ساختن نشان خطِ آهنگ شدنی نبود."""


