# نسبت‌های سرعتی که آزموده می‌شود.
#
# چرا لازم است: هم‌بستگیِ لغزان جابه‌جاییِ زمانی را می‌بخشد ولی
# **کِششِ** زمانی را نه. مداح هر شب اندکی تندتر یا کندتر می‌خواند، و
# سنجش نشان داد همان اندازه بس است که «همان نوحه» را از ۰٫۶۹ به
# ۰٫۶۰ بیندازد — یعنی درست همان جایی که این لایه باید کار کند و
# نمی‌کرد.
#
# پنج نسبت از ۰٫۸ تا ۱٫۲۵ بازهٔ راستینِ تفاوتِ اجرا را می‌پوشاند.
# بیش از این، هزینه‌اش برابرِ سود نیست.
TEMPO_RATIOS = (0.80, 0.90, 1.0, 1.11, 1.25)


def _restretch(sig: np.ndarray, ratio: float) -> np.ndarray:
    """
    نشان را در زمان می‌کِشد یا می‌فشرد.

    درون‌یابیِ خطی روی محور زمان؛ گام دست‌نخورده می‌ماند چون تنها
    ستون‌ها بازنمونه‌برداری می‌شوند نه سطرها.
    """
    length = sig.shape[1]
    new_length = max(2, int(round(length * ratio)))
    if new_length == length:
        return sig
    source = np.linspace(0, length - 1, new_length)
    out = np.empty((12, new_length), dtype=np.float32)
    grid = np.arange(length)
    for row in range(12):
        out[row] = np.interp(source, grid, sig[row])
    norms = np.linalg.norm(out, axis=0, keepdims=True)
    norms[norms < 1e-9] = 1.0
    return out / norms


def compare(query: np.ndarray, target: np.ndarray) -> tuple[float, int, int]:
    """
    پارهٔ کاربر را بر سراسر یک نوا می‌لغزاند.

    بازگشتی: (بیشترین هم‌بستگی، جای فریم، جابه‌جایی گام به نیم‌پرده)

    دو چیز آزموده می‌شود، چون اجرای دیگر در هر دو فرق می‌کند:

    • **گام** — دوازده چرخش. مداح هر شب در گام دیگری می‌خواند؛ اگر
      تنها گامِ خودش را می‌سنجیدیم، همان نوحه در گام دیگر بیگانه
      می‌نمود.
    • **سرعت** — پنج نسبت. لغزاندن، جابه‌جایی را می‌بخشد ولی کشش را
      نه؛ و کشش همان چیزی است که دو اجرا را از هم دور می‌کند.
    """
    q_len, t_len = query.shape[1], target.shape[1]
    if q_len == 0 or t_len == 0:
        return 0.0, 0, 0

    # پارهٔ درازتر از نوا: جایشان را عوض می‌کنیم تا لغزاندن معنا بدهد
    if q_len > t_len:
        score, _offset, shift = compare(target, query)
        return score, 0, -shift

    best = (-1.0, 0, 0)
    for ratio in TEMPO_RATIOS:
        stretched = _restretch(query, ratio)
        if stretched.shape[1] > t_len:
            continue
        # هم‌بستگی با هر دو سو هنجارشده، برابر است با میانگینِ
        # حاصل‌ضرب نقطه‌ای ستون‌به‌ستون — و آن را می‌شود برای همهٔ
        # جای‌ها یکجا و برداری حساب کرد.
        for shift in range(12):
            rolled = np.roll(stretched, shift, axis=0)
            scores = _sliding_scores(rolled, target)
            if scores.size == 0:
                continue
            index = int(np.argmax(scores))
            value = float(scores[index])
            if value > best[0]:
                # چرخش بالای ۶، به‌آسانی به‌عنوان چرخش منفی خوانده می‌شود
                semitones = shift if shift <= 6 else shift - 12
                # `index` جای پنجره در **هدف** است، و هدف کشیده
                # نشده — پرس‌وجو کشیده شده. تقسیم بر ratio، جای
                # یافته را تا ۲۵٪ جابه‌جا می‌کرد.
                best = (value, int(index), semitones)

    return best


def _sliding_scores(query: np.ndarray, target: np.ndarray) -> np.ndarray:
    """
    هم‌بستگی پاره با نوا، برای هر جای ممکن — یکجا و برداری.

    پیاده‌سازیِ ساده‌لوحانه یک حلقهٔ پایتونی روی همهٔ جاها می‌خواست
    و برای پنج هزار نوا، دقیقه‌ها می‌برد. با پنجرهٔ لغزانِ numpy،
    همان کار در چند میلی‌ثانیه انجام می‌شود.
    """
    q_len, t_len = query.shape[1], target.shape[1]
    positions = t_len - q_len + 1
    if positions <= 0:
        return np.empty(0, dtype=np.float32)

    # نمای لغزان: (۱۲ × جاها × درازای پاره) بی رونوشت گرفتن
    windows = np.lib.stride_tricks.sliding_window_view(target, q_len, axis=1)
    # ضرب نقطه‌ای ستون‌به‌ستون، سپس میانگین بر درازای پاره
    return np.einsum("ct,cpt->p", query, windows) / q_len


def _profile(sig: np.ndarray) -> np.ndarray:
    """نمایهٔ درشت: میانگین کرومای سراسر نوا، هنجارشده. دوازده عدد."""
    mean = sig.mean(axis=1)
    norm = float(np.linalg.norm(mean))
    return mean / norm if norm > 1e-9 else mean


def _shortlist(
    query: np.ndarray, corpus: list[tuple[int, np.ndarray]]
) -> list[tuple[int, np.ndarray]]:
    """
    کوتاه‌فهرستی از نامزدهایی که ارزش سنجش کامل دارند.

    گنجینهٔ کوچک اصلاً پالوده نمی‌خواهد؛ سنجشِ همه ارزان‌تر از
    ساختنِ کوتاه‌فهرست است.
    """
    if len(corpus) <= SHORTLIST:
        return corpus

    q_profile = _profile(query)
    # بهترین از میان دوازده چرخش گام — همان ناوابستگی به گام، ولی
    # روی دوازده عدد به جای سراسر نشان.
    rotations = np.stack([np.roll(q_profile, k) for k in range(12)])

    ranked: list[tuple[float, int, np.ndarray]] = []
    for track_id, target in corpus:
        score = float(np.max(rotations @ _profile(target)))
        ranked.append((score, track_id, target))

    ranked.sort(key=lambda item: item[0], reverse=True)
    return [(track_id, sig) for _score, track_id, sig in ranked[:SHORTLIST]]


def search(
    query: np.ndarray,
    corpus: list[tuple[int, np.ndarray]],
    limit: int = 3,
) -> list[MelodyMatch]:
    """
    نزدیک‌ترین نواهای گنجینه بر پایهٔ خطِ آهنگ.

    فهرست تهی، پاسخِ درست و رایج است — نه نشانهٔ خرابی.
    """
    if len(corpus) < MIN_CORPUS:
        return []

    scored: list[MelodyMatch] = []
    for track_id, target in _shortlist(query, corpus):
        try:
            similarity, frame, semitones = compare(query, target)
        except Exception:  # noqa: BLE001
            continue
        scored.append(
            MelodyMatch(
                track_id=track_id,
                similarity=similarity,
                offset_seconds=frame / FRAMES_PER_SECOND,
                semitones=semitones,
            )
        )

    if not scored:
        return []

    scored.sort(key=lambda m: m.similarity, reverse=True)

    # آستانهٔ مطلق **و** حاشیه نسبت به دومین نامزد. تنها یکی از این
    # دو بس نیست: با آستانهٔ تنها، شبِ پرهیاهو همه را بالا می‌برد؛ با
    # حاشیهٔ تنها، دو نوای بی‌ربط که یکی اندکی نزدیک‌تر است، پاسخ
    # می‌شوند.
    best = scored[0]
    if best.similarity < MIN_SIMILARITY:
        return []
    if len(scored) > 1 and (best.similarity - scored[1].similarity) < MIN_MARGIN:
        return []

    return [m for m in scored[:limit] if m.similarity >= MIN_SIMILARITY]
