def signature(audio: np.ndarray) -> np.ndarray:
    """
    نشان خطِ آهنگ: آرایه‌ای ۱۲×N از float32، هر ستون هنجارشده.

    ستون‌ها زمان‌اند و سطرها دوازده نتِ گام.
    """
    import librosa

    if audio.size < MIN_SECONDS * SAMPLE_RATE:
        raise MelodyError(
            f"برای نشان خطِ آهنگ دست‌کم {MIN_SECONDS:.0f} ثانیه آوا بایسته است."
        )

    try:
        chroma = librosa.feature.chroma_cqt(
            y=audio, sr=SAMPLE_RATE, hop_length=CHROMA_HOP
        )
    except Exception as exc:  # noqa: BLE001
        # chroma_cqt گاه روی آوای بسیار کوتاه یا خاموش می‌شکند؛
        # chroma_stft کم‌دقت‌تر است ولی همیشه کار می‌کند.
        logger.debug("chroma_cqt نشد (%s)؛ به chroma_stft بازمی‌گردیم.", exc)
        chroma = librosa.feature.chroma_stft(
            y=audio, sr=SAMPLE_RATE, hop_length=CHROMA_HOP
        )

    return _smooth_and_normalize(chroma)


def _smooth_and_normalize(chroma: np.ndarray) -> np.ndarray:
    """
    هموار می‌کند، نمونه‌برداری را کم می‌کند، و هر ستون را هنجار.

    هموارسازی پیش از کم کردنِ نمونه‌ها انجام می‌شود نه پس از آن —
    وگرنه آنچه دور می‌ریزیم همان چیزی است که باید میانگین می‌گرفتیم.
    """
    frames = chroma.shape[1]
    usable = (frames // SMOOTH) * SMOOTH
    if usable < SMOOTH:
        raise MelodyError("آوا برای هموارسازی بسنده نیست.")

    folded = chroma[:, :usable].reshape(12, usable // SMOOTH, SMOOTH)
    smoothed = folded.mean(axis=2)

    # هنجارسازیِ هر ستون: بلندی صدا از نشان بیرون می‌رود
    norms = np.linalg.norm(smoothed, axis=0, keepdims=True)
    norms[norms < 1e-9] = 1.0
    return (smoothed / norms).astype(np.float32)


def to_bytes(sig: np.ndarray) -> bytes:
    """
    نشان را برای نشاندن در پایگاه داده می‌فشرد.

    هر مقدار پس از هنجارسازی میان ۰ و ۱ است، پس یک بایت بس است.
    نوای پنج‌دقیقه‌ای ≈ ۲۰۰ فریم × ۱۲ = ۲٫۴ کیلوبایت. برای پنج هزار
    نوا، ۱۲ مگابایت — در برابر یک گیگابایتِ اثر انگشت، هیچ.
    """
    return np.clip(sig * 255.0, 0, 255).astype(np.uint8).tobytes()


def from_bytes(raw: bytes) -> np.ndarray:
    """نشان را بازمی‌گرداند و دگربار هنجار می‌کند."""
    flat = np.frombuffer(raw, dtype=np.uint8).astype(np.float32) / 255.0
    if flat.size % 12:
        raise MelodyError("نشان خطِ آهنگ ناقص است.")
    sig = flat.reshape(12, flat.size // 12)
    norms = np.linalg.norm(sig, axis=0, keepdims=True)
    norms[norms < 1e-9] = 1.0
    return sig / norms


